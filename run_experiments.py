def get_last_exp_num() -> int:
    max_num = 0
    for parent_dir in [MODELS_DIR, RESULTS_DIR]:
        if not parent_dir.exists():
            continue
        for path in parent_dir.glob('exp_*'):
            if path.is_dir():
                try:
                    num = int(path.name.split('_')[-1])
                    if num > max_num:
                        max_num = num
                except (ValueError, IndexError):
                    continue
    return max_num

