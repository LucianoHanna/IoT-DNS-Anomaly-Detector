def run_experiment_and_benchmark(exp_id: int):
    stdout_suppressed = subprocess.DEVNULL
    stderr_suppressed = subprocess.DEVNULL
    
    print("--- Building Docker image ---")
    subprocess.run(
        ["docker", "compose", "build"], 
        check=True, stdout=stdout_suppressed, stderr=stderr_suppressed
    )

    print("--- Running experiment (train and evaluate) ---")
    subprocess.run(
        ["docker", "compose", "run", "--rm", "botnet-detector", "all"], 
        check=True, stdout=stdout_suppressed, stderr=stderr_suppressed
    )
    
    print(f"--- Running benchmark for exp_{exp_id} ---")
    subprocess.run(
        ["docker", "compose", "run", "--rm", "botnet-detector", "benchmark", str(exp_id)],
        check=True, stdout=stdout_suppressed, stderr=stderr_suppressed
    )

def parse_results(exp_num: int) -> Dict[str, Any]:
    results = {
        "accuracy": "N/A", "precision": "N/A", "recall": "N/A",
        "f1_score": "N/A", "fp_rate": "N/A", "inference_ms": "N/A", "throughput": "N/A",
        "dga_recall": {}
    }
    summary_file = RESULTS_DIR / f'exp_{exp_num}' / f'results_summary_exp_{exp_num}.txt'
    benchmark_file = RESULTS_DIR / f'exp_{exp_num}' / 'benchmark_results.json'

    if summary_file.exists():
        content = summary_file.read_text()
        results["accuracy"] = f"{float(re.search(r'Accuracy: (\S+)', content).group(1)) * 100:.5f}"
        results["precision"] = f"{float(re.search(r'Precision: (\S+)', content).group(1)) * 100:.5f}"
        results["recall"] = f"{float(re.search(r'Recall \(Detection Rate\): (\S+)', content).group(1)) * 100:.5f}"
        results["f1_score"] = f"{float(re.search(r'F1 Score: (\S+)', content).group(1)) * 100:.5f}"
        results["fp_rate"] = f"{float(re.search(r'False Positive Rate: (\S+)', content).group(1)) * 100:.5f}"
        
        # Parse DGA recall rates
        dga_section_match = re.search(r'Detection Rate by DGA Family:\n(.*?)(?:\n\n|$)', content, re.DOTALL)
        if dga_section_match:
            dga_lines = dga_section_match.group(1).strip().split('\n')
            for line in dga_lines:
                match = re.match(r'([^:]+):\s+(\S+)', line)
                if match:
                    family = match.group(1).strip()
                    recall_val = float(match.group(2)) * 100
                    results["dga_recall"][family] = f"{recall_val:.5f}"

    if benchmark_file.exists():
        with open(benchmark_file, 'r') as f:
            data = json.load(f)
        
        target_benchmark = next((b for b in data.get('benchmarks', []) if b.get('name') == 'test_predict_batch_medium'), None)
        
        if target_benchmark:
            stats = target_benchmark.get('stats', {})
            extra_info = target_benchmark.get('extra_info', {})
            
            mean_time_s = stats.get('mean')
            if mean_time_s is not None and mean_time_s > 0:
                results["inference_ms"] = f"{mean_time_s * 1000:.2f}"

            mean_rps = extra_info.get('mean_rps')
            if mean_rps is not None and mean_rps > 0:
                results["throughput"] = f"{mean_rps:.0f}"

    return results

def generate_summary_table(title: str, file_path: Path, start_exp: int, end_exp: int, experiments: List[Dict[str, Any]]):
    print("\n" + "=" * 50)
    print(f"  Generating Summary: {title}")
    print("=" * 50)

    header = "| Experimento | Acurácia (%) | Precisão (%) | Recall (%) | F1-Score (%) | Falsos Positivos (%) | Tempo de Inferência (ms) | Throughput (domínios/s) |"
    separator = "| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |"
    
    rows = [header, separator]
    exp_index = 0
    for i in range(start_exp, end_exp + 1):
        name = experiments[exp_index]['name']
        metrics = parse_results(i)
        row = (
            f"| **{name}** (Exp {i}) | {metrics['accuracy']} | {metrics['precision']} | {metrics['recall']} | "
            f"{metrics['f1_score']} | {metrics['fp_rate']} | {metrics['inference_ms']} | {metrics['throughput']} |"
        )
        rows.append(row)
        exp_index += 1
    
    table = "\n".join(rows)
    file_path.write_text(f"### {title}\n{table}\n")
    print(f"Summary table generated at: {file_path}")
    print(table)

def generate_dga_recall_table(title: str, file_path: Path, start_exp: int, end_exp: int, experiments: List[Dict[str, Any]]):
    print("\n" + "=" * 50)
    print(f"  Generating DGA Recall Summary: {title}")
    print("=" * 50)

    all_dga_families = set()
    experiment_results = []
    for i in range(start_exp, end_exp + 1):
        metrics = parse_results(i)
        experiment_results.append(metrics['dga_recall'])
        all_dga_families.update(metrics['dga_recall'].keys())
    
    sorted_families = sorted(list(all_dga_families))

    header_parts = ["| Família DGA |"]
    exp_names = [exp['name'] for exp in experiments]
    header_parts.extend([f" {name} (%) |" for name in exp_names])
    header = "".join(header_parts)
    
    separator_parts = ["| :--- |"]
    separator_parts.extend([" :---: |" for _ in experiments])
    separator = "".join(separator_parts)

    rows = [header, separator]
    for family in sorted_families:
        row_parts = [f"| {family} |"]
        for exp_result in experiment_results:
            recall = exp_result.get(family, "0.00000")
            row_parts.append(f" {recall} |")
        rows.append("".join(row_parts))

    table = "\n".join(rows)
    file_path.write_text(f"### {title}\n{table}\n")
    print(f"DGA recall summary table generated at: {file_path}")
    print(table)

